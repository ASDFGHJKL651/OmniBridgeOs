void ed25519_test(void)
{
    failures = 0;

    uint8_t priv[64], pub[32], sig[64];

    /* ---------- TEST 1 ---------- */
    if (ed25519_keypair_from_seed(T1_SK, priv, pub) == 0 &&
        mem_eq(pub, T1_PK, 32)) {
        serial_printf("[ED25519-TEST] OK  : RFC8032 TEST 1 (empty)\n");
    } else {
        serial_printf("[ED25519-TEST] FAIL: RFC8032 TEST 1 (empty)\n");
        failures++;
    }

    {
        int rc = ed25519_sign(priv, "", 0, sig);
        check("TEST 1 SIG matches RFC8032",
              rc == 0 && mem_eq(sig, T1_SIG, 64));
    }
    {
        int v = ed25519_verify(T1_PK, "", 0, T1_SIG);
        check("TEST 1 verify passes", v == 1);
    }

    /* ---------- TEST 2 ---------- */
    if (ed25519_keypair_from_seed(T2_SK, priv, pub) == 0 &&
        mem_eq(pub, T2_PK, 32)) {
        serial_printf("[ED25519-TEST] OK  : RFC8032 TEST 2 (1 byte 0x72)\n");
    } else {
        serial_printf("[ED25519-TEST] FAIL: RFC8032 TEST 2 (1 byte 0x72)\n");
        failures++;
    }

    {
        int rc = ed25519_sign(priv, T2_MSG, 1, sig);
        check("TEST 2 SIG matches RFC8032",
              rc == 0 && mem_eq(sig, T2_SIG, 64));
    }
    {
        int v = ed25519_verify(T2_PK, T2_MSG, 1, T2_SIG);
        check("TEST 2 verify passes", v == 1);
    }

    /* ---------- TEST 3 ---------- */
    if (ed25519_keypair_from_seed(T3_SK, priv, pub) == 0 &&
        mem_eq(pub, T3_PK, 32)) {
        serial_printf("[ED25519-TEST] OK  : RFC8032 TEST 3 (2 bytes 0xaf 0x82)\n");
    } else {
        serial_printf("[ED25519-TEST] FAIL: RFC8032 TEST 3\n");
        failures++;
    }

    {
        int rc = ed25519_sign(priv, T3_MSG, 2, sig);
        check("TEST 3 SIG matches RFC8032",
              rc == 0 && mem_eq(sig, T3_SIG, 64));
    }
    {
        int v = ed25519_verify(T3_PK, T3_MSG, 2, T3_SIG);
        check("TEST 3 verify passes", v == 1);
    }

    /* ---------- 负向测试 ---------- */

    /* 篡改签名 1 字节 */
    {
        uint8_t bad[64];
        for (int i = 0; i < 64; ++i) bad[i] = T1_SIG[i];
        bad[0] ^= 0x01;
        int v = ed25519_verify(T1_PK, "", 0, bad);
        check("tampered signature rejected", v == 0);
    }

    /* 篡改消息 1 字节（相对 T2） */
    {
        uint8_t bad_msg[1] = { 0x73 };   /* 期望为 0x72 */
        int v = ed25519_verify(T2_PK, bad_msg, 1, T2_SIG);
        check("tampered message rejected", v == 0);
    }

    /* 篡改公钥 1 字节 */
    {
        uint8_t bad_pk[32];
        for (int i = 0; i < 32; ++i) bad_pk[i] = T1_PK[i];
        bad_pk[0] ^= 0x01;
        int v = ed25519_verify(bad_pk, "", 0, T1_SIG);
        check("tampered pubkey rejected", v == 0);
    }

    /* NULL msg + len > 0：签名与验证都必须拒绝 */
    {
        int rs = ed25519_sign(priv, 0, 10, sig);
        check("sign(NULL, 10) rejected", rs != 0);

        int rv = ed25519_verify(T1_PK, 0, 10, T1_SIG);
        check("verify(NULL, 10) rejected", rv == 0);
    }

    /* NULL msg + len == 0：允许 */
    {
        uint8_t s0[64];
        int rs = ed25519_sign(priv, 0, 0, s0);
        check("sign(NULL, 0) accepted", rs == 0);
    }

    if (failures == 0) {
        serial_printf("[ED25519-TEST] selftest OK\n");
    } else {
        serial_printf("[ED25519-TEST] selftest FAILED: %d case(s)\n",
                      failures);
    }
}
